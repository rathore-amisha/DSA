public class switchstatement {
    public static void main(String[] args){
        int number = 2;
        switch(number){
            case 1:System.out.println("fan");
            break;
            case 2:System.out.println("bulb");
            break;
            case 3:System.out.println("ac");
            break;
            default:System.out.println("not applicable");
        }
    }
}
