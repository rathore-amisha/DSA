public class bitManupulation {
    public static void main(String[] args) {
        System.out.println(5&6); //AND Operator use ans=4
        System.out.println(5|6); //OR Operator use ans=7
        System.out.println(5^6); //XOR Operator use ans=3
        System.out.println(~5); //binary ones complement Operator use ans=-6
        System.out.println(~0); //-1
        System.out.println(5<<2); //binary left shift ans=20
        System.out.println(6>>1); //binary right shift ans=3
    }
}
